-- Drill mode (Phase 6): drill run state, the simulation's effect log, scenario approval.

-- ─── Drill runs ─────────────────────────────────────────────────────
alter table drill_runs drop constraint drill_runs_status_check;
alter table drill_runs add constraint drill_runs_status_check check (status in ('running', 'paused', 'ended'));
alter table drill_runs
  add column company_id uuid references companies(id),
  add column incident_id uuid,
  add column tick integer not null default 0 check (tick >= 0),
  add column difficulty integer not null default 2 check (difficulty between 1 and 5),
  add column seconds_per_tick integer not null default 20 check (seconds_per_tick >= 5),
  add column agents_enabled boolean not null default true,
  add column facilitator_person_id uuid,
  add column audit_requested_at timestamptz;
update drill_runs d set company_id = w.company_id from worlds w where w.id = d.world_id;
alter table drill_runs alter column company_id set not null;
alter table drill_runs add foreign key (world_id, incident_id) references incidents(world_id, id);
alter table drill_runs add foreign key (world_id, facilitator_person_id) references people(world_id, id);
alter table drill_runs alter column status set default 'paused';

-- ─── Scenarios ──────────────────────────────────────────────────────
-- A scenario runs only after a facilitator approves its preview (AGENTS.md: run_scenario).
alter table scenarios
  add column source text not null default 'library' check (source in ('library', 'builder')),
  add column approved_by uuid,
  add column approved_at timestamptz;
create unique index scenarios_library_title on scenarios(company_id, title) where source = 'library';

-- ─── Simulation effects ─────────────────────────────────────────────
-- Everything the simulation did, tick by tick: triggers, twists, saboteur actions, facilitator
-- injections, and the hidden spread. Append-only; a reversal is a new row pointing at the effect.
-- Hidden rows (the true spread) never reach players' browsers.
create table sim_effects (
  world_id uuid not null,
  company_id uuid not null,
  id bigint generated by default as identity,
  tick integer not null check (tick >= 0),
  actor text not null check (actor in ('engine', 'trigger', 'twist', 'spread', 'hunter', 'ambusher', 'flanker', 'wanderer', 'facilitator', 'ai_seat')),
  effect_type text not null,
  target_table text,
  target_id uuid,
  target_label text,
  description text not null,
  hidden boolean not null default false,
  reversible boolean not null default false,
  reverses_effect_id bigint,
  payload jsonb not null default '{}',
  created_at timestamptz not null default now(),
  primary key (world_id, id),
  foreign key (world_id, company_id) references worlds(id, company_id),
  foreign key (world_id, reverses_effect_id) references sim_effects(world_id, id)
);
create index sim_effects_by_tick on sim_effects(world_id, tick, id);
alter table sim_effects enable row level security;

create trigger sim_effects_append_only before update or delete on sim_effects
  for each row execute function forbid_mutation();
create trigger sim_effects_no_truncate before truncate on sim_effects
  for each statement execute function forbid_mutation();

-- Field reports from the simulation (carrier delays, retests) are records like any other.
alter table records drop constraint records_record_type_check;
alter table records add constraint records_record_type_check
  check (record_type in ('maintenance', 'cleaning', 'sop', 'test_result', 'batch_record', 'field_report'));

-- ─── Read access for the drill screens ──────────────────────────────
alter table drill_runs enable row level security;
create policy "company members read drill runs" on drill_runs
  for select to authenticated using (company_id in (select public.current_company_ids()));
create policy "company members read visible sim effects" on sim_effects
  for select to authenticated using (company_id in (select public.current_company_ids()) and not hidden);

